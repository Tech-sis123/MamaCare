/**
 * Finds all glossary terms present in a snippet of text for interactive tooltips/modals.
 */
export function findGlossaryTerms(text) {
  if (!text || typeof text !== 'string') return [];
  const found = [];
  const lower = text.toLowerCase();

  for (const [term, data] of Object.entries(MEDICAL_GLOSSARY)) {
    if (lower.includes(term.toLowerCase())) {
      found.push({ term, ...data });
    }
  }

  return found;
}
